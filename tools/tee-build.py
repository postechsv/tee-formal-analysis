#!/usr/bin/env python3
"""tee-build: build a case study.

Usage
    python3 tools/tee-build.py case-studies/NAME [--mode plain|dmc|m2l] [--invisible] [--spec DIR]

case-studies/NAME/NAME.toml says what the analyzed system is:
    [spec] features   the API feature groups of the spec that the model uses (mk/features.mk, in
                      lower case with hyphens); every other group is dropped
    [ghost...]        ghost attributes of spec objects (tools/ghost.py)
How it is analyzed is chosen here: --mode (plain build, DM-Check build, maude2lean build) and
--invisible (the invisible-transition reduction of the paper).

The spec is built with the Makefile into build/<build name>/ (NAME, NAME-dmc, NAME-m2l, with -inv
for --invisible), and build/<build name>/main.maude loads it and then case-studies/NAME/cmd/main.maude,
the entry module of the case study.
"""

import argparse
import os
import re
import subprocess
import sys
import tomllib

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))


def api_features():
    with open(os.path.join(ROOT, 'mk', 'features.mk'), encoding='utf-8') as fh:
        m = re.search(r'^FEATURES\s*:=\s*(.*)$', fh.read(), re.MULTILINE)
    return [f for f in m.group(1).split() if f != 'INVISIBLE']


def main(argv):
    ap = argparse.ArgumentParser(description='Build a case study.')
    ap.add_argument('case', help='case-studies/NAME')
    ap.add_argument('--mode', choices=('plain', 'dmc', 'm2l'), default='plain')
    ap.add_argument('--invisible', action='store_true')
    ap.add_argument('--spec', help='spec checkout (default: the submodule spec/)')
    args = ap.parse_args(argv)

    case_dir = os.path.normpath(os.path.join(os.getcwd(), args.case))
    name = os.path.basename(case_dir)
    manifest = os.path.join(case_dir, name + '.toml')
    with open(manifest, 'rb') as fh:
        data = tomllib.load(fh)

    known = api_features()
    wanted = data.get('spec', {}).get('features', [])
    flags = {f: '0' for f in known}
    for f in wanted:
        var = f.upper().replace('-', '_')
        if var not in flags:
            sys.exit('%s: unknown feature %s (known: %s)' % (manifest, f,
                     ', '.join(k.lower().replace('_', '-') for k in known)))
        flags[var] = '1'

    build = name + ('' if args.mode == 'plain' else '-' + args.mode) + ('-inv' if args.invisible else '')
    make = ['make', '--no-print-directory', '-C', ROOT, 'NAME=' + build, 'WITHOUT=']
    make += ['%s=%s' % kv for kv in sorted(flags.items())]
    make += ['DMC=%d' % (args.mode != 'plain'), 'M2L=%d' % (args.mode == 'm2l'),
             'INVISIBLE=%d' % args.invisible,
             'GHOST=' + (os.path.relpath(manifest, ROOT) if 'ghost' in data else '')]
    if args.spec:
        make.append('SPEC=' + args.spec)
    make.append('src')
    if subprocess.run(make).returncode:
        return 1

    out = os.path.join(ROOT, 'build', build)
    entry = os.path.relpath(os.path.join(case_dir, 'cmd', 'main'), out)
    with open(os.path.join(out, 'main.maude'), 'w', encoding='utf-8') as fh:
        fh.write('--- Generated by tools/tee-build.py from %s: the spec of this build, then the case study.\n'
                 'load src/main\nload %s\n' % (os.path.relpath(manifest, ROOT), entry))
    print('tee-build: %s' % os.path.relpath(os.path.join(out, 'main.maude'), os.getcwd()))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
