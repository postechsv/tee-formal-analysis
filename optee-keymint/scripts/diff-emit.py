#!/usr/bin/env python3
"""Emit output/diff/cases.h: the cases of every scenario as C strings for kmk-ca batch (kmk_ca.c)."""
import glob
import os

rows = []
for path in sorted(glob.glob('output/diff/*.cases')):
    scen = os.path.basename(path).split('.')[0]
    for line in open(path):
        ops = line.strip().split('|')[0]
        rows.append((scen, ops))
with open('output/diff/cases.h', 'w') as f:
    f.write('/* generated by scripts/diff-emit.py: %d cases */\n' % len(rows))
    f.write('static const char *CASE_SCEN[] = {\n')
    for scen, _ in rows:
        f.write('    "%s",\n' % scen)
    f.write('};\n')
    f.write('static const char *CASE_OPS[] = {\n')
    for _, ops in rows:
        f.write('    "%s",\n' % ops)
    f.write('};\n')
    f.write('#define NCASES %d\n' % len(rows))
print('cases.h: %d cases' % len(rows))
