#!/usr/bin/env python3
"""tee-build: build a case study.

Usage
    python3 tools/tee-build.py case-studies/NAME [--mode plain|dmc|m2l] [--invisible] [--spec DIR]

case-studies/NAME/NAME.toml says what the analyzed system is:
    [ghost]           ghost attributes of spec objects (tools/ghost.py)
    [invisible]       the rules turned into equations with --invisible (tools/gen-invisible.py)
    [ta.KEY]          a trusted application translated from C (tools/ta2imp.py)
Every API feature group of the spec (mk/features.mk) is on.
How it is analyzed is chosen here: --mode (plain build, DM-Check build, maude2lean build) and
--invisible (the invisible-transition reduction of the paper).

The spec is built with the Makefile into build/<build name>/ (NAME, NAME-dmc, NAME-m2l, with -inv
for --invisible), and the TAs are translated into build/<build name>/ta/.  build/<build name>/model.maude
loads the spec, case-studies/NAME/main.maude (the model files) and the TAs; main.maude loads model.maude
and case-studies/NAME/cmd/main.maude, the entry module of the analyses.
"""

import argparse
import os
import re
import subprocess
import sys
import tomllib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ta2imp  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))


def api_features():
    with open(os.path.join(ROOT, 'mk', 'features.mk'), encoding='utf-8') as fh:
        m = re.search(r'^FEATURES\s*:=\s*(.*)$', fh.read(), re.MULTILINE)
    return [f for f in m.group(1).split() if f != 'INVISIBLE']


def main(argv):
    ap = argparse.ArgumentParser(description='Build a case study.')
    ap.add_argument('case', help='case-studies/NAME')
    ap.add_argument('--mode', choices=('plain', 'dmc', 'm2l'), default='plain')
    ap.add_argument('--invisible', action='store_true')
    ap.add_argument('--spec', help='spec checkout (default: the submodule spec/)')
    args = ap.parse_args(argv)

    case_dir = os.path.normpath(os.path.join(os.getcwd(), args.case))
    name = os.path.basename(case_dir)
    manifest = os.path.join(case_dir, name + '.toml')
    with open(manifest, 'rb') as fh:
        data = tomllib.load(fh)

    # every feature on, passed explicitly so that a cached setting of the build is overridden
    flags = {f: '1' for f in api_features()}

    build = name + ('' if args.mode == 'plain' else '-' + args.mode) + ('-inv' if args.invisible else '')
    make = ['make', '--no-print-directory', '-C', ROOT, 'NAME=' + build, 'WITHOUT=']
    make += ['%s=%s' % kv for kv in sorted(flags.items())]
    make += ['DMC=%d' % (args.mode != 'plain'), 'M2L=%d' % (args.mode == 'm2l'),
             'INVISIBLE=%d' % args.invisible,
             'GHOST=' + (os.path.relpath(manifest, ROOT) if 'ghost' in data else ''),
             'INVISIBLE_G=' + (os.path.relpath(manifest, ROOT) if args.invisible else '')]
    if args.invisible and 'invisible' not in data:
        sys.exit('%s: --invisible needs an [invisible] table' % manifest)
    if args.spec:
        make.append('SPEC=' + args.spec)
    make.append('src')
    if subprocess.run(make).returncode:
        return 1

    out = os.path.join(ROOT, 'build', build)
    tas = []
    try:
        for key, table in data.get('ta', {}).items():
            path = os.path.join(out, 'ta', table.get('output', key + '.maude'))
            ta2imp.translate(manifest, key, path)
            print('tee-build: ta.%s -> %s' % (key, os.path.relpath(path, os.getcwd())))
            tas.append(os.path.relpath(path, out))
    except ta2imp.TransError as ex:
        sys.exit('tee-build: ta2imp: %s' % ex)
    rel = lambda p: os.path.relpath(p, out)
    with open(os.path.join(out, 'model.maude'), 'w', encoding='utf-8') as fh:
        fh.write('--- Generated by tools/tee-build.py from %s: the spec of this build, the model files and\n'
                 '--- the translated TAs.\nload src/main\nload %s\n%s'
                 % (os.path.relpath(manifest, ROOT), rel(os.path.join(case_dir, 'main')),
                    ''.join('load %s\n' % os.path.splitext(t)[0] for t in tas)))
    with open(os.path.join(out, 'main.maude'), 'w', encoding='utf-8') as fh:
        fh.write('--- Generated by tools/tee-build.py: the model, then the entry module of the analyses.\n'
                 'load model\nload %s\n' % rel(os.path.join(case_dir, 'cmd', 'main')))
    print('tee-build: %s' % os.path.relpath(os.path.join(out, 'main.maude'), os.getcwd()))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
